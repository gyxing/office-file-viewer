/** 根据解析格式选择对应的文件图标类别。 */
function getFileGlyphKind(previewKind?: PreviewKind): FileGlyphKind {
  if (!previewKind) return 'generic';
  if (isWordPreviewKind(previewKind)) return 'word';
  if (isSpreadsheetPreviewKind(previewKind)) return 'excel';
  if (isPresentationPreviewKind(previewKind)) return 'powerpoint';
  return 'generic';
}

/** 渲染与当前 Office 格式对应的彩色文件图标。 */
export function OfficeFileTypeIcon({
  previewKind,
  className,
  ...props
}: OfficeFileTypeIconProps) {
  const mergedClassName = ['office-file-type-icon', className]
    .filter(Boolean)
    .join(' ');

  return (
    <svg
      {...props}
      aria-hidden="true"
      className={mergedClassName}
      focusable="false"
      height="1em"
      viewBox="0 0 1024 1024"
      width="1em"
    >
      {FILE_TYPE_GLYPHS[getFileGlyphKind(previewKind)]}
    </svg>
  );
}
